// The language Home Assistant is set to for this user: the profile language
// first, then the server's, then the browser's. Returned as given ("it",
// "pt-BR"), because dates want the full tag and strings only the first part.
export function langOf(hass) {
  return hass?.locale?.language || hass?.language
    || (typeof navigator !== 'undefined' && navigator.language) || 'en';
}

// Look a key up, falling back to English. Dotted keys reach into groups
// ("lbl.person"). {name} placeholders are filled from `vars`. A key that exists
// nowhere comes back as itself, which makes a typo obvious on screen.
export function t(hass, key, vars) {
  const base = String(langOf(hass)).toLowerCase().split(/[-_]/)[0];
  const find = lang => key.split('.').reduce((o, k) => (o == null ? o : o[k]), STRINGS[lang]);
  let s = find(base);
  if (s == null) s = find('en');
  if (s == null) return key;
  if (typeof s !== 'string') return s;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)) : s;
}
